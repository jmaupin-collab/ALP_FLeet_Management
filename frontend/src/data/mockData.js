const MAINT_STATUSES = new Set(["open", "in_progress", "waiting_parts"]);
const DEPLOYED = new Set(["deployed", "in_transit"]);

export function dashboardKpis() {
  const byType = ASSET_TYPES.map((asset_type) => {
    const group = assets.filter((a) => a.asset_type === asset_type);
    const in_maintenance = group.filter((a) => a.open_work_orders > 0).length;
    const deployed = group.filter((a) => a.open_work_orders === 0 && DEPLOYED.has(a.current_status)).length;
    const idle_or_stored = group.length - in_maintenance - deployed;
    const downtime = workOrders
      .filter((w) => w.asset_type === asset_type)
      .reduce((sum, w) => sum + w.downtime_hours, 0);
    return {
      asset_type,
      total_assets: group.length,
      deployed,
      in_maintenance,
      idle_or_stored,
      total_purchase_cost: group.reduce((s, a) => s + a.initial_purchase_cost, 0),
      downtime_hours_ytd: downtime,
    };
  });
  return {
    fleet_size: assets.length,
    deployed: byType.reduce((s, r) => s + r.deployed, 0),
    in_maintenance: byType.reduce((s, r) => s + r.in_maintenance, 0),
    total_purchase_cost: assets.reduce((s, a) => s + a.initial_purchase_cost, 0),
    downtime_hours_ytd: workOrders.reduce((s, w) => s + w.downtime_hours, 0),
    by_asset_type: byType,
  };
}

